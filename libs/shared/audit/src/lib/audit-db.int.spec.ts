import { fileURLToPath } from 'node:url';
import { beforeEach, describe, expect, it } from 'vitest';
import { sql } from 'drizzle-orm';
import { drizzle } from 'drizzle-orm/node-postgres';
import { migrate } from 'drizzle-orm/node-postgres/migrator';
// pg is CJS — default-import the module object (named exports aren't ESM-exposed, N12).
import pg from 'pg';
import {
  DateTimeService,
  ensureTestDatabase,
  failIfDbTestsRequired,
} from '@sanad/database';
import {
  AUDIT_IMMUTABILITY_ERROR_CODE,
  AUDIT_IMMUTABILITY_SQL,
  auditTestResetSql,
} from './audit-immutability.constants.js';
import { auditLogTable } from './audit-log.table.js';
import type { AuditDb, AuditScope } from './audit-entry.types.js';
import { DrizzleAuditStore } from './drizzle-audit-store/drizzle-audit-store.js';
import { AuditRecorder } from './nest/audit-recorder/audit-recorder.js';
import { REDACTED } from './redact/redact.js';

// The dedicated test DB (TDD2). Created by infra/postgres/init/01-create-databases.sql on a
// fresh volume, and by `ensureTestDatabase` on a machine whose volume predates it.
const TEST_DB_URL = 'postgresql://sanad:sanad@localhost:5440/audit_test';

// Resolve the migrations dir from THIS file, never the CWD — a CWD-relative path made
// `migrate()` throw and six suites SILENTLY skip once (rules change-log 2026-07-19).
const MIGRATIONS_DIR = fileURLToPath(new URL('./migrations', import.meta.url));

const scope: AuditScope = {
  actor: {
    userId: '11111111-1111-4111-8111-111111111111',
    role: 'admin',
    type: 'user',
  },
  context: { ip: '85.10.1.4', userAgent: 'Mozilla/5.0', requestId: 'req-42' },
};

/**
 * The DRIVER's refusal, not Drizzle's wrapper. Drizzle rethrows as `Failed query: …` with the
 * real Postgres error on `cause` — asserting on the wrapper would pass for ANY failing query,
 * which is the opposite of proving the trigger fired.
 */
async function refusalOf(
  work: Promise<unknown>,
): Promise<{ message: string; code: string | undefined }> {
  try {
    await work;
  } catch (error) {
    const cause = (error as { cause?: unknown }).cause ?? error;
    return {
      message: String((cause as { message?: unknown }).message ?? cause),
      code: (cause as { code?: string }).code,
    };
  }
  throw new Error('expected the statement to be refused, but it succeeded');
}

async function tryConnect(): Promise<pg.Pool | null> {
  try {
    await ensureTestDatabase(TEST_DB_URL);
  } catch (error) {
    console.warn(
      `audit_test could not be created (${String(error instanceof Error ? error.message : error)})`,
    );
    failIfDbTestsRequired(TEST_DB_URL, error);
    return null;
  }
  const pool = new pg.Pool({
    connectionString: TEST_DB_URL,
    options: '-c timezone=UTC',
  });
  try {
    await pool.query('select 1');
    await migrate(drizzle(pool), { migrationsFolder: MIGRATIONS_DIR });
    // The trigger is not generated by drizzle-kit — an adopting service applies this same
    // constant in a `--custom` migration (U3: one source for the guard).
    await pool.query(AUDIT_IMMUTABILITY_SQL);
    return pool;
  } catch (error) {
    // Report WHY we're skipping — a silent skip hides a real migration failure as "green".
    console.warn(
      `audit_test unavailable (${String(error instanceof Error ? error.message : error)})`,
    );
    await pool.end().catch(() => undefined);
    failIfDbTestsRequired(TEST_DB_URL, error);
    return null;
  }
}

const pool = await tryConnect();
const describeDb = pool ? describe : describe.skip;
if (!pool) {
  console.warn(
    'audit_test unreachable — skipping DB integration tests (TDD2). Start the dev Postgres to run them.',
  );
}

describeDb('audit trail (audit_test, TDD2)', () => {
  const activePool = pool;
  if (!activePool) {
    return; // never reached (the suite is skipped) — narrows the type for TS
  }
  const db = drizzle(activePool);
  const exec = db as unknown as AuditDb;
  const clock = DateTimeService.fixed('2026-08-09T09:00:00.000Z');
  const store = new DrizzleAuditStore();
  const recorder = new AuditRecorder(store, clock);

  beforeEach(async () => {
    // The ONE sanctioned reset, and only against `audit_test` (TDD2): disarm the truncate guard,
    // truncate, re-arm. Plain TRUNCATE used to work here — that was the bug, not the feature.
    await db.execute(sql.raw(auditTestResetSql()));
  });

  it('writes a complete row with actor, ip, user-agent and before/after', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, {
        action: 'settings.updated',
        entityType: 'setting',
        entityId: 'branding.brand.name',
        before: { value: 'Sanad' },
        after: { value: 'Sanad Tech' },
      });
    });
    const rows = await db.select().from(auditLogTable);
    expect(rows).toHaveLength(1);
    expect(rows[0]).toMatchObject({
      actorUserId: scope.actor.userId,
      actorRole: 'admin',
      actorType: 'user',
      action: 'settings.updated',
      entityType: 'setting',
      entityId: 'branding.brand.name',
      before: { value: 'Sanad' },
      after: { value: 'Sanad Tech' },
      ip: '85.10.1.4',
      userAgent: 'Mozilla/5.0',
      requestId: 'req-42',
      outcome: 'succeeded',
    });
  });

  // ── The phase's named acceptance proof: the row is IMMUTABLE ─────────────────────────
  it('REFUSES an UPDATE at the database level', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, { action: 'a.b', entityType: 't' });
    });
    const refusal = await refusalOf(
      db.execute(sql`update "audit_log" set action = 'tampered'`),
    );
    expect(refusal.message).toMatch(/append-only/i);
    expect(refusal.code).toBe(AUDIT_IMMUTABILITY_ERROR_CODE);
    const [row] = await db.select().from(auditLogTable);
    expect(row?.action).toBe('a.b');
  });

  // TRUNCATE bypasses row-level triggers entirely, so `before update or delete` alone left the
  // whole trail erasable by one statement — which is not what "append-only" means to anyone
  // relying on it as evidence. Found by noticing a row had vanished from the real settings DB.
  it('REFUSES a TRUNCATE at the database level', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, { action: 'a.b', entityType: 't' });
    });
    const refusal = await refusalOf(
      db.execute(sql`truncate table "audit_log"`),
    );
    expect(refusal.message).toMatch(/append-only/i);
    expect(refusal.code).toBe(AUDIT_IMMUTABILITY_ERROR_CODE);
    expect(await db.select().from(auditLogTable)).toHaveLength(1);
  });

  it('REFUSES a DELETE at the database level', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, { action: 'a.b', entityType: 't' });
    });
    const refusal = await refusalOf(db.execute(sql`delete from "audit_log"`));
    expect(refusal.message).toMatch(/append-only/i);
    expect(refusal.code).toBe(AUDIT_IMMUTABILITY_ERROR_CODE);
    expect(await db.select().from(auditLogTable)).toHaveLength(1);
  });

  it('never persists a secret — redaction happens at the store, not at the call site', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, {
        action: 'integration.configured',
        entityType: 'integration',
        before: {},
        after: { host: 'smtp.example.com', SMTP_PASSWORD: 'hunter2' },
      });
    });
    const [row] = await db.select().from(auditLogTable);
    expect(row?.after).toEqual({
      host: 'smtp.example.com',
      SMTP_PASSWORD: REDACTED,
    });
    expect(JSON.stringify(row)).not.toContain('hunter2');
  });

  it('leaves NO row when the caller’s transaction rolls back', async () => {
    const client = await activePool.connect();
    try {
      await client.query('begin');
      await recorder.runInScope(scope, async () => {
        await recorder.recordWithin(drizzle(client) as unknown as AuditDb, {
          action: 'settings.updated',
          entityType: 'setting',
        });
      });
      await client.query('rollback');
    } finally {
      client.release();
    }
    expect(await db.select().from(auditLogTable)).toHaveLength(0);
  });

  it('records a FAILED attempt with its localized key — a refused write is evidence too', async () => {
    await recorder.runInScope(scope, async () => {
      await recorder.recordWithin(exec, {
        action: 'settings.updated',
        entityType: 'setting',
        outcome: 'failed',
        failureKey: 'auth.forbidden',
      });
    });
    const [row] = await db.select().from(auditLogTable);
    expect(row).toMatchObject({
      outcome: 'failed',
      failureKey: 'auth.forbidden',
    });
  });

  it('writes a batch in one statement', async () => {
    await recorder.runInScope(scope, async () => {
      recorder.record({ action: 'a.one', entityType: 't' });
      recorder.record({ action: 'a.two', entityType: 't' });
      await recorder.flush(exec);
    });
    expect(await db.select().from(auditLogTable)).toHaveLength(2);
  });
});
